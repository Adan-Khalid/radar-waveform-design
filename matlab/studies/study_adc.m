%STUDY_ADC Detection loss of 1 to 4-bit receivers against an unquantized one (LFM,
%   BT 64), with fewer trials than the Python run so it fits a MATLAB Online session.
%   Writes reports/matlab/adc_losses.csv and adc_pfa_check.csv. Takes a few minutes;
%   if MATLAB Online stops it, halve opts.noiseStats and opts.trials and run again.

root = radarwave.repoRoot();
outDir = fullfile(root, 'reports', 'matlab');
if ~isfolder(outDir), mkdir(outDir); end

opts = struct( ...
    'pfa', 1e-4, ...
    'pdTarget', 0.9, ...
    'noiseStats', 1e6, ...       % noise-only statistics per threshold (Python: 2e6)
    'trials', 8000, ...          % trials per SNR on the fine grid (Python: 20000)
    'coarseTrials', 2000, ...
    'bootstrap', 500, ...
    'seed', 2026, ...
    'fineHalfWidth', 1.0, ...
    'fineStep', 0.1, ...
    'maxSnrDb', 60);

s = radarwave.lfm(64, 1);
receivers = [radarwave.makeReceiver(), radarwave.makeReceiver(4), radarwave.makeReceiver(3), ...
    radarwave.makeReceiver(2), radarwave.makeReceiver(1), ...
    radarwave.makeReceiver(3, 'midrise', 'subtractive'), ...
    radarwave.makeReceiver(1, 'midrise', 'nonsubtractive')];

tic;
[lossTable, pfaTable] = radarwave.runReceivers(s, receivers, opts);
fprintf('ADC study finished in %.0f s\n', toc);
writetable(lossTable, fullfile(outDir, 'adc_losses.csv'));
writetable(pfaTable, fullfile(outDir, 'adc_pfa_check.csv'));
disp(lossTable);
disp(pfaTable);
