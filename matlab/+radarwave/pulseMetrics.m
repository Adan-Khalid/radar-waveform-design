function m = pulseMetrics(s, ref, samplesPerCell)
%PULSEMETRICS PSL, ISL, -3 dB width (cells) and mismatch loss of s through ref.
if nargin < 2 || isempty(ref), ref = s; end
if nargin < 3, samplesPerCell = 1; end
y = radarwave.correlate(s, ref);
m = struct( ...
    'psl_db', radarwave.pslDb(y), ...
    'isl_db', radarwave.islDb(y), ...
    'width_3db_cells', radarwave.widthCells(y, -3, samplesPerCell), ...
    'mismatch_loss_db', radarwave.mismatchLossDb(s, ref));
end
